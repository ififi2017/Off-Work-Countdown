// Generates the Watch's copy table from the iOS String Catalog.
//
// watchOS only needs these few strings, so the Watch app and its widgets carry
// a small Swift table instead of a bundled catalog. Since plan 019 L2a the
// values come from Localizable.xcstrings rather than public/locales, so the
// Watch reads exactly the copy the phone does. `npm run check:ios` runs this
// with `--check`.
//
// Run: node scripts/generate-watch-localizations.mjs [--check]

import { readFileSync, writeFileSync } from "node:fs";

export const watchLocalizationKeys = [
  "watchWaitingForIPhone", "watchConfirmPlusOnIPhone", "watchSyncExpired", "watchOpenIPhone",
  "watchTimeLeftTitle", "watchTimeLeft", "watchOffAt", "watchOvertimeUntil", "watchBackAt", "watchNextShiftAt",
  "watchPlusIncludes", "watchPlusOnIPhone", "watchWidgetDescription",
];
export const watchLocalizationsPath = "src-mobile/ios/WatchApp/WatchLocalizations.generated.swift";
// Spelled out rather than imported: generate-ios-xcstrings.mjs imports the key
// list above, and the two modules should not import each other.
const catalogPath = "src-mobile/ios/App/App/Localizable.xcstrings";

const locales = ["en", "zh-CN", "zh-HK", "zh-TW", "ja", "ko", "de", "es", "fr", "it", "pt", "ru", "ar", "hi-IN", "mr-IN", "id", "th", "tr", "vi"];
const quote = (value) => JSON.stringify(value).replaceAll("\\u2028", "\\u{2028}");

export const createWatchLocalizations = (catalog) => {
  const rows = locales.map((locale) => {
    const values = watchLocalizationKeys.map((key) => {
      const value = catalog.strings?.[key]?.localizations?.[locale]?.stringUnit?.value;
      if (typeof value !== "string" || value.length === 0) throw new Error(`${locale} is missing ${key} in ${catalogPath}`);
      return `            ${quote(key)}: ${quote(value)}`;
    }).join(",\n");
    return `        ${quote(locale)}: [\n${values}\n        ]`;
  }).join(",\n");
  return `// Generated by scripts/generate-watch-localizations.mjs. Do not edit.\nimport Foundation\n\nnonisolated enum WatchLocalizations {\n    private static let values: [String: [String: String]] = [\n${rows}\n    ]\n\n    static func text(_ key: String, localeIdentifier: String? = nil) -> String {\n        let candidates = localeIdentifier.map { [$0] } ?? Locale.preferredLanguages\n        let locale = resolveLocale(candidates)\n        return values[locale]?[key] ?? values["en"]?[key] ?? key\n    }\n\n    static func resolveLocale(_ candidates: [String]) -> String {\n        for raw in candidates {\n            let normalized = raw.replacingOccurrences(of: "_", with: "-")\n            if let exact = values.keys.first(where: { $0.caseInsensitiveCompare(normalized) == .orderedSame }) { return exact }\n            let lower = normalized.lowercased()\n            if lower.hasPrefix("zh-hant-hk") || lower.hasPrefix("zh-hk") { return "zh-HK" }\n            if lower.hasPrefix("zh-hant") || lower.hasPrefix("zh-tw") { return "zh-TW" }\n            if lower.hasPrefix("zh") { return "zh-CN" }\n            if let language = values.keys.first(where: {\n                lower.hasPrefix($0.lowercased() + "-") || $0.lowercased().hasPrefix(lower + "-")\n            }) { return language }\n        }\n        return "en"\n    }\n}\n`;
};

const isEntryPoint = process.argv[1]?.endsWith("generate-watch-localizations.mjs");
if (isEntryPoint) {
  const output = createWatchLocalizations(JSON.parse(readFileSync(catalogPath, "utf8")));
  if (process.argv.includes("--check")) {
    if (readFileSync(watchLocalizationsPath, "utf8") !== output) throw new Error(`${watchLocalizationsPath} is stale; run node scripts/generate-watch-localizations.mjs`);
  } else writeFileSync(watchLocalizationsPath, output);
}
