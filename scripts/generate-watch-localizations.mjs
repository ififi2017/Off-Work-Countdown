// Generates the Watch's copy table from the iOS String Catalog.
//
// watchOS only needs these few strings, so the Watch app and its widgets carry
// a small Swift table instead of a bundled catalog. Since plan 019 L2a the
// values come from Localizable.xcstrings rather than public/locales, so the
// Watch reads exactly the copy the phone does. `npm run check:ios` runs this
// with `--check`.
//
// Run: node scripts/generate-watch-localizations.mjs [--check]

import { readFileSync, writeFileSync } from "node:fs";
import { AMERICAN_ENGLISH_REGIONS, LATIN_AMERICAN_REGIONS } from "./regional-variants.mjs";

export const watchLocalizationKeys = [
  "watchCacheCorrupt", "watchUpdateRequired", "watchWaitingForIPhone", "watchSyncExpired", "watchOpenIPhone",
  "watchTimeLeftTitle", "watchTimeLeft", "watchOffAt", "watchOvertimeUntil", "watchBackAt", "watchNextShiftAt",
  "watchWidgetDescription",
];
export const watchLocalizationsPath = "src-mobile/ios/WatchApp/WatchLocalizations.generated.swift";
// Spelled out rather than imported: check-ios-strings.mjs imports the key list
// above, and the two modules should not import each other.
const catalogPath = "src-mobile/ios/App/App/Localizable.xcstrings";

const locales = ["en", "zh-CN", "zh-HK", "zh-TW", "ja", "ko", "de", "es", "fr", "it", "pt", "ru", "ar", "hi-IN", "mr-IN", "id", "th", "tr", "vi"];
const partialLocales = [
  { id: "en-GB", fallback: "en" },
  { id: "es-MX", fallback: "es" },
];
const supported = ["en", "en-GB", "zh-CN", "zh-HK", "zh-TW", "ja", "ko", "de", "es", "es-MX", "fr", "it", "pt", "ru", "ar", "hi-IN", "mr-IN", "id", "th", "tr", "vi"];
const quote = (value) => JSON.stringify(value).replaceAll("\\u2028", "\\u{2028}");
const swiftList = (items) => items.map((item) => quote(item)).join(", ");

function catalogValue(catalog, key, locale) {
  const value = catalog.strings?.[key]?.localizations?.[locale]?.stringUnit?.value;
  return typeof value === "string" && value.length > 0 ? value : null;
}

export const createWatchLocalizations = (catalog) => {
  const rows = locales.map((locale) => {
    const values = watchLocalizationKeys.map((key) => {
      const value = catalogValue(catalog, key, locale);
      if (value == null) throw new Error(`${locale} is missing ${key} in ${catalogPath}`);
      return `            ${quote(key)}: ${quote(value)}`;
    }).join(",\n");
    return `        ${quote(locale)}: [\n${values}\n        ]`;
  });
  for (const { id, fallback } of partialLocales) {
    const pairs = [];
    for (const key of watchLocalizationKeys) {
      const value = catalogValue(catalog, key, id);
      const parent = catalogValue(catalog, key, fallback);
      if (value != null && value !== parent) pairs.push(`            ${quote(key)}: ${quote(value)}`);
    }
    if (pairs.length > 0) rows.splice(rows.findIndex((row) => row.startsWith(`        ${quote(fallback)}:`)) + 1, 0, `        ${quote(id)}: [\n${pairs.join(",\n")}\n        ]`);
  }
  return `// Generated by scripts/generate-watch-localizations.mjs. Do not edit.
import Foundation

nonisolated enum WatchLocalizations {
    /// Every language the phone can pin, including regional variants whose
    /// table below only stores strings that differ from the parent.
    private static let supported = [${swiftList(supported)}]
    private static let americanEnglishRegions: Set<String> = [${swiftList(AMERICAN_ENGLISH_REGIONS)}]
    private static let latinAmericanRegions: Set<String> = [${swiftList(LATIN_AMERICAN_REGIONS)}]
    private static let values: [String: [String: String]] = [
${rows.join(",\n")}
    ]

    static func text(_ key: String, localeIdentifier: String? = nil) -> String {
        let candidates = localeIdentifier.map { [$0] } ?? Locale.preferredLanguages
        let locale = resolveLocale(candidates)
        if let value = values[locale]?[key] { return value }
        if let parent = parentLocale(locale), let value = values[parent]?[key] { return value }
        return values["en"]?[key] ?? key
    }

    /// Same region tables as \`NativeLocalizer.resolve\` and Android \`AppLanguages.resolve\`.
    /// Keep \`scripts/regional-variants.mjs\` in step with these sets.
    static func resolveLocale(_ candidates: [String]) -> String {
        for raw in candidates {
            let normalized = raw.replacingOccurrences(of: "_", with: "-")
            if let exact = supported.first(where: { $0.caseInsensitiveCompare(normalized) == .orderedSame }) { return exact }
            let lower = normalized.lowercased()
            if lower.hasPrefix("zh-hant-hk") || lower.hasPrefix("zh-hk") { return "zh-HK" }
            if lower.hasPrefix("zh-hant") || lower.hasPrefix("zh-tw") { return "zh-TW" }
            if lower.hasPrefix("zh") { return "zh-CN" }
            if lower == "en" || lower.hasPrefix("en-") { return isAmericanEnglish(lower) ? "en" : "en-GB" }
            if lower == "es" || lower.hasPrefix("es-") { return isLatinAmerican(lower) ? "es-MX" : "es" }
            if let language = supported.first(where: {
                lower.hasPrefix($0.lowercased() + "-") || $0.lowercased().hasPrefix(lower + "-")
            }) { return language }
        }
        return "en"
    }

    private static func parentLocale(_ locale: String) -> String? {
        switch locale {
        case "en-GB": return "en"
        case "es-MX": return "es"
        default: return nil
        }
    }

    private static func regionCode(_ tag: String) -> String? {
        let parts = tag.split(separator: "-").map(String.init)
        guard parts.count >= 2 else { return nil }
        var index = 1
        if parts[index].count == 4, parts[index].allSatisfy(\\.isLetter) {
            index += 1
            guard index < parts.count else { return nil }
        }
        let region = parts[index]
        let letters = region.count == 2 && region.allSatisfy(\\.isLetter)
        let digits = region.count == 3 && region.allSatisfy(\\.isNumber)
        return (letters || digits) ? region.uppercased() : nil
    }

    private static func isAmericanEnglish(_ tag: String) -> Bool {
        guard let region = regionCode(tag) else { return true }
        return americanEnglishRegions.contains(region)
    }

    private static func isLatinAmerican(_ tag: String) -> Bool {
        guard let region = regionCode(tag) else { return false }
        return latinAmericanRegions.contains(region)
    }
}
`;
};

const isEntryPoint = process.argv[1]?.endsWith("generate-watch-localizations.mjs");
if (isEntryPoint) {
  const output = createWatchLocalizations(JSON.parse(readFileSync(catalogPath, "utf8")));
  if (process.argv.includes("--check")) {
    if (readFileSync(watchLocalizationsPath, "utf8") !== output) throw new Error(`${watchLocalizationsPath} is stale; run node scripts/generate-watch-localizations.mjs`);
  } else writeFileSync(watchLocalizationsPath, output);
}
