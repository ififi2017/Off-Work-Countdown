import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

// 把本地化的产品名生成为 macOS 的 `.lproj/InfoPlist.strings`，让 Finder、程序坞、
// 启动台和聚焦按系统语言显示应用名，而不是一律显示英文。
//
// 名称取自 public/locales/<locale>/translation.json 的 `offWorkCountdown`——也就是
// 应用界面自己用的那个标题。系统里显示的名字必须和用户在应用里看到的一致；商店
// 商品页的名字（docs/msstore-listing-titles.csv）是另一回事，两者本来就有出入，
// 例如 zh-TW 界面是「下班倒數計時」而商店是「下班倒數計時器」。
//
// 两个键都要写：
//   - CFBundleDisplayName —— Finder / 程序坞 / 启动台 / 聚焦；
//   - CFBundleName —— 菜单栏最左侧那个粗体应用名。这个**只能**在这里改：AppKit
//     的应用菜单标题由系统从 bundle 名派生，给第一个 Submenu 设标题会被忽略
//     （lib.rs 里那条 labels.app_name 因此只对「关于」面板生效，菜单栏纹丝不动，
//     实机验证过）。
//
// CFBundleName 有 15 字符的长度建议，fr / es / pt / hi 几种远超过，菜单栏上会占
// 掉不少宽度。但截断产品名比让它一律显示英文更糟，这里照原样写。
const LOCALES_DIR = "public/locales";
const NAME_KEY = "offWorkCountdown";
const OUTPUT_DIR = "src-tauri/macos-lproj";
const INFO_PLIST = "src-tauri/Info.plist";

/**
 * i18n locale → macOS `.lproj` 目录名。
 *
 * 不能直接拿 locale 当目录名，苹果的解析规则和项目里的键不是一套：
 *   zh-CN  → zh-Hans、zh-TW → zh-Hant，直接写 zh-CN.lproj 不会被命中；
 *   zh-HK  → zh-HK（实测 zh-Hant-HK 和 zh-HK 两种偏好都落到它，不是 zh-Hant）；
 *   hi-IN / mr-IN → hi / mr，带地区反而匹配不上 hi-IN 的用户偏好；
 *   pt     → pt，单条即可同时接住 pt-BR 与 pt-PT（分别写反而会漏掉另一边）。
 * 以上都用 Bundle.preferredLocalizations（macOS 选 .lproj 的实际算法）实测过。
 */
const LPROJ_BY_LOCALE = {
  en: "en",
  "zh-CN": "zh-Hans",
  "zh-TW": "zh-Hant",
  "zh-HK": "zh-HK",
  ja: "ja",
  ko: "ko",
  fr: "fr",
  de: "de",
  es: "es",
  it: "it",
  pt: "pt",
  ru: "ru",
  "hi-IN": "hi",
  "mr-IN": "mr",
  tr: "tr",
  ar: "ar",
  th: "th",
  id: "id",
  vi: "vi",
};

/** .strings 是 C 风格字面量，反斜杠和引号必须转义。 */
function escapeStringsValue(value) {
  return value.replace(/\\/g, "\\\\").replace(/"/g, '\\"');
}

// 以 public/locales 下实际存在的目录为准，而不是脚本里另抄一份语言清单。
// 新增一种语言时只会在缺少 .lproj 映射这一处失败，不会两边各漏一半。
const locales = readdirSync(LOCALES_DIR, { withFileTypes: true })
  .filter((entry) => entry.isDirectory())
  .map((entry) => entry.name)
  .sort();

const generated = [];
for (const locale of locales) {
  const lproj = LPROJ_BY_LOCALE[locale];
  // 新增语言时必须显式补一条映射。默认拿 locale 当目录名会静默产出一个永远
  // 匹配不上的 .lproj，那种失败没有任何征兆——宁可让构建停下来。
  if (!lproj) {
    console.error(
      `No macOS .lproj mapping for locale "${locale}". Add it to LPROJ_BY_LOCALE in scripts/generate-macos-lproj.mjs.`
    );
    process.exit(1);
  }

  const translationPath = resolve(LOCALES_DIR, locale, "translation.json");
  const productName = JSON.parse(readFileSync(translationPath, "utf8"))[
    NAME_KEY
  ]?.trim();
  if (!productName) {
    console.error(`${translationPath} has no "${NAME_KEY}" string.`);
    process.exit(1);
  }
  generated.push({ lproj, productName });
}

if (generated.length === 0) {
  console.error(`${LOCALES_DIR} produced no localizations.`);
  process.exit(1);
}

const duplicate = generated
  .map((entry) => entry.lproj)
  .find((lproj, index, all) => all.indexOf(lproj) !== index);
if (duplicate) {
  console.error(`Two locales both map to ${duplicate}.lproj.`);
  process.exit(1);
}

// 整目录重建：改过映射或删掉某个语言后，残留的旧 .lproj 会被继续打进包里。
rmSync(OUTPUT_DIR, { recursive: true, force: true });
for (const { lproj, productName } of generated) {
  const directory = resolve(OUTPUT_DIR, `${lproj}.lproj`);
  mkdirSync(directory, { recursive: true });
  writeFileSync(
    resolve(directory, "InfoPlist.strings"),
    `/* Generated by scripts/generate-macos-lproj.mjs from ${LOCALES_DIR}/<locale>/translation.json. Do not edit. */\n` +
      `"CFBundleDisplayName" = "${escapeStringsValue(productName)}";\n` +
      `"CFBundleName" = "${escapeStringsValue(productName)}";\n`,
    "utf8"
  );
}

const generatedLocalizations = generated.map((entry) => entry.lproj);

// Info.plist 的 CFBundleLocalizations 必须和真实存在的 .lproj 一一对应。
// 多声明一个，系统会认为应用支持某语言却取不到名字；少声明一个，那份 .lproj
// 可能根本不被查询。两种都不会报错，只会安静地显示错名字，所以在这里拦。
const infoPlist = readFileSync(INFO_PLIST, "utf8");
const declaredBlock = infoPlist.match(
  /<key>CFBundleLocalizations<\/key>\s*<array>([\s\S]*?)<\/array>/
);
if (!declaredBlock) {
  console.error(`${INFO_PLIST} has no CFBundleLocalizations array.`);
  process.exit(1);
}
const declared = [...declaredBlock[1].matchAll(/<string>([^<]*)<\/string>/g)].map(
  (match) => match[1]
);
const missing = generatedLocalizations.filter((l) => !declared.includes(l));
const extra = declared.filter((l) => !generatedLocalizations.includes(l));
if (missing.length > 0 || extra.length > 0) {
  console.error(
    `${INFO_PLIST} CFBundleLocalizations is out of sync with ${LOCALES_DIR}.` +
      (missing.length > 0 ? `\n  missing: ${missing.join(", ")}` : "") +
      (extra.length > 0 ? `\n  unexpected: ${extra.join(", ")}` : "")
  );
  process.exit(1);
}

console.log(
  `Generated ${generated.length} macOS .lproj bundles in ${OUTPUT_DIR}: ${generatedLocalizations.join(", ")}`
);
