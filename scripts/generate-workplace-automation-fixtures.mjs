import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";

// Plan 021: the workplace automation rule fixture is hand-written JSON in the
// Android test resources, where A1 reads it. iOS compiles the same text into
// AppTests: the test target has no resources phase, and Xcode Cloud runs
// tests on a host without the source tree.

export const workplaceAutomationFixtureJsonPath = resolve(
  "src-mobile/android/core/domain/src/test/resources/workplace-automation-fixtures.json"
);
export const workplaceAutomationFixtureSwiftPath = resolve(
  "src-mobile/ios/App/AppTests/WorkplaceAutomationFixtures.generated.swift"
);

export function createWorkplaceAutomationFixtureSwift() {
  const json = readFileSync(workplaceAutomationFixtureJsonPath, "utf8").replace(/\r\n/g, "\n").trimEnd();
  JSON.parse(json);
  if (json.includes('"#')) throw new Error("The fixture may not contain \"# (it ends the Swift raw string).");
  return [
    "// Generated by scripts/generate-workplace-automation-fixtures.mjs from",
    "// src-mobile/android/core/domain/src/test/resources/workplace-automation-fixtures.json.",
    "// Do not edit by hand; edit the JSON and run npm run generate:workplace-automation-fixtures.",
    "nonisolated enum WorkplaceAutomationFixtureData {",
    '    static let json = #"""',
    json,
    '"""#',
    "}",
    "",
  ].join("\n");
}

/** Returns null when the Swift copy matches the JSON, else a message. */
export function checkWorkplaceAutomationFixtures() {
  let current = "";
  try {
    current = readFileSync(workplaceAutomationFixtureSwiftPath, "utf8");
  } catch {
    return `${workplaceAutomationFixtureSwiftPath} is missing. Run npm run generate:workplace-automation-fixtures.`;
  }
  return current === createWorkplaceAutomationFixtureSwift()
    ? null
    : "WorkplaceAutomationFixtures.generated.swift is stale. Run npm run generate:workplace-automation-fixtures.";
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  if (process.argv.includes("--check")) {
    const problem = checkWorkplaceAutomationFixtures();
    if (problem) {
      console.error(problem);
      process.exit(1);
    }
    console.log("Workplace automation fixtures are up to date.");
  } else {
    writeFileSync(workplaceAutomationFixtureSwiftPath, createWorkplaceAutomationFixtureSwift());
    console.log(`Wrote ${workplaceAutomationFixtureSwiftPath}`);
  }
}
