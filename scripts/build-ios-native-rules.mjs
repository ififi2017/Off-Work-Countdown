import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import ts from "typescript";

const modules = [
  ["./countdown", resolve("lib/countdown.ts")],
  ["./reminders", resolve("lib/reminders.ts")],
  ["./summary", resolve("lib/summary.ts")],
];

function compileModule(path) {
  const source = readFileSync(path, "utf8");
  return ts.transpileModule(source, {
    compilerOptions: {
      module: ts.ModuleKind.CommonJS,
      target: ts.ScriptTarget.ES2020,
      removeComments: false,
    },
    fileName: path,
    reportDiagnostics: true,
  });
}

export function createIOSNativeRulesBundle() {
  const compiled = modules.map(([name, path]) => {
    const result = compileModule(path);
    const errors = (result.diagnostics ?? []).filter(
      (diagnostic) => diagnostic.category === ts.DiagnosticCategory.Error
    );
    if (errors.length > 0) {
      throw new Error(
        `Could not compile ${path}: ${errors
          .map((diagnostic) => diagnostic.messageText)
          .join(", ")}`
      );
    }
    return `${JSON.stringify(name)}: function(module, exports, require) {\n${result.outputText}\n}`;
  });

  return `// Generated by scripts/build-ios-native-rules.mjs. Do not edit by hand.
// SwiftUI calls this JavaScriptCore bundle so lib/countdown.ts and
// lib/reminders.ts remain the product's only schedule-rule implementations.
(function(global) {
  "use strict";
  const factories = {${compiled.join(",\n")}};
  const cache = Object.create(null);
  function require(name) {
    if (cache[name]) return cache[name].exports;
    const factory = factories[name];
    if (!factory) throw new Error("Unknown bundled module: " + name);
    const loadedModule = { exports: {} };
    cache[name] = loadedModule;
    factory(loadedModule, loadedModule.exports, require);
    return loadedModule.exports;
  }

  const countdown = require("./countdown");
  const reminders = require("./reminders");
  const summary = require("./summary");

  function buildShift(input) {
    return countdown.buildShiftTimeline(
      input.startTime,
      input.endTime,
      new Date(input.nowMs),
      {
        breakStartTime: input.breakStartTime || null,
        breakDurationMinutes: input.breakDurationMinutes || 0,
        overtimeEndAtMs: input.overtimeEndAtMs || null,
      }
    );
  }

  global.OWCNative = {
    snapshot(inputJSON) {
      const input = JSON.parse(inputJSON);
      const shift = buildShift(input);
      const nextShift = countdown.findNextShiftTimeline({
        startTime: input.startTime,
        endTime: input.endTime,
        workdays: input.workdays,
        schedule: input.schedule || null,
        afterMs: Math.max(input.nowMs, countdown.getShiftEndAtMs(shift)),
        options: {
          breakStartTime: input.breakStartTime || null,
          breakDurationMinutes: input.breakDurationMinutes || 0,
        },
      });
      const dailySalary = countdown.getDailySalary(
        String(input.salaryAmount ?? ""),
        input.salaryType,
        input.monthlyWorkingDays,
        input.annualBonusMonths || 0
      );
      return JSON.stringify({
        segments: shift.segments,
        startAtMs: countdown.getShiftStartAtMs(shift),
        endAtMs: countdown.getShiftEndAtMs(shift),
        plannedEndAtMs: shift.plannedEndAtMs,
        overtimeEndAtMs: shift.overtimeEndAtMs,
        durationMs: countdown.getShiftDurationMs(shift),
        plannedDurationMs: countdown.getPlannedShiftDurationMs(shift),
        elapsedMs: countdown.getShiftElapsedMs(shift, input.nowMs),
        remainingMs: countdown.getShiftRemainingMs(shift, input.nowMs),
        progress: countdown.calculateTimelineProgress(shift, input.nowMs),
        payRatio: countdown.calculateTimelinePayRatio(shift, input.nowMs),
        activeBreakEndAtMs: countdown.getActiveBreakEndAtMs(shift, input.nowMs),
        isWorkday: countdown.isScheduledWorkday(
          new Date(countdown.getShiftStartAtMs(shift)),
          input.workdays,
          input.schedule || null
        ),
        nextRestAtMs: countdown.findNextRestDate({
          afterMs: input.nowMs,
          workdays: input.workdays,
          schedule: input.schedule || null,
        })?.getTime() ?? null,
        dailySalary,
        nextShiftStartAtMs: nextShift
          ? countdown.getShiftStartAtMs(nextShift)
          : null,
        nextShiftEndAtMs: nextShift
          ? countdown.getShiftEndAtMs(nextShift)
          : null,
      });
    },

    summarize(inputJSON) {
      const input = JSON.parse(inputJSON);
      const asOf = new Date(input.asOfMs);
      const periodStart = input.period === "year"
        ? summary.startOfYear(asOf)
        : summary.startOfWeek(asOf);
      return JSON.stringify(summary.summarize({
        periodStart,
        asOf,
        workdays: input.workdays,
        schedule: input.schedule || null,
        currentShiftStart: new Date(input.currentShiftStartMs),
        currentShiftEnd: new Date(input.currentShiftEndMs),
        plannedDailyHours: input.plannedDailyHours,
        todayProgress: input.todayProgress,
        dailySalary: input.dailySalary,
        todayEffectiveHours: input.todayEffectiveHours,
        todayPayRatio: input.todayPayRatio,
      }));
    },

    reminders(inputJSON) {
      const input = JSON.parse(inputJSON);
      const shift = buildShift(input);
      const nextShift = countdown.findNextShiftTimeline({
        startTime: input.startTime,
        endTime: input.endTime,
        workdays: input.workdays,
        schedule: input.schedule || null,
        afterMs: Math.max(input.nowMs, countdown.getShiftEndAtMs(shift)),
        options: {
          breakStartTime: input.breakStartTime || null,
          breakDurationMinutes: input.breakDurationMinutes || 0,
        },
      });
      const project = (timeline, scope) =>
        reminders
          .buildShiftReminders(timeline, input.reminderInputs)
          .map((reminder) => ({
            ...reminder,
            id: scope + ":" + countdown.getShiftEndAtMs(timeline) + ":" + reminder.id,
          }));
      return JSON.stringify(
        [
          ...project(shift, "current"),
          ...(nextShift ? project(nextShift, "next") : []),
        ].sort((left, right) => left.atMs - right.atMs)
      );
    },

    validateBreak(inputJSON) {
      const input = JSON.parse(inputJSON);
      if (!input.breakStartTime || !(input.breakDurationMinutes > 0)) return true;
      return buildShift(input).segments.length > 1;
    },
  };
})(globalThis);
`;
}

if (process.argv[1] === new URL(import.meta.url).pathname) {
  writeFileSync(
    resolve("src-mobile/ios/App/App/Resources/CountdownRules.js"),
    createIOSNativeRulesBundle(),
    "utf8"
  );
}
