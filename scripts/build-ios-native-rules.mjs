import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import ts from "typescript";

const moduleSources = {
  "./countdown": resolve("lib/countdown.ts"),
  "./reminders": resolve("lib/reminders.ts"),
  "./summary": resolve("lib/summary.ts"),
  "./watch-projection": resolve("lib/watch-projection.ts"),
};

function compileModule(path) {
  const source = readFileSync(path, "utf8");
  return ts.transpileModule(source, {
    compilerOptions: {
      module: ts.ModuleKind.CommonJS,
      target: ts.ScriptTarget.ES2020,
      removeComments: false,
    },
    fileName: path,
    reportDiagnostics: true,
  });
}

// Every rules script starts from the countdown module.
const SHARED_GLUE = `
  const countdown = require("./countdown");
`;

/**
 * A self-contained script evaluating the named `lib/` modules, the shared
 * glue, then `body`, which assigns its entry points onto `global`.
 */
export function createRulesScript({ header, moduleNames, body }) {
  const compiled = moduleNames.map((name) => {
    const path = moduleSources[name];
    const result = compileModule(path);
    const errors = (result.diagnostics ?? []).filter(
      (diagnostic) => diagnostic.category === ts.DiagnosticCategory.Error
    );
    if (errors.length > 0) {
      throw new Error(
        `Could not compile ${path}: ${errors
          .map((diagnostic) => diagnostic.messageText)
          .join(", ")}`
      );
    }
    return `${JSON.stringify(name)}: function(module, exports, require) {\n${result.outputText}\n}`;
  });

  return `${header}
(function(global) {
  "use strict";
  const factories = {${compiled.join(",\n")}};
  const cache = Object.create(null);
  function require(name) {
    if (cache[name]) return cache[name].exports;
    const factory = factories[name];
    if (!factory) throw new Error("Unknown bundled module: " + name);
    const loadedModule = { exports: {} };
    cache[name] = loadedModule;
    factory(loadedModule, loadedModule.exports, require);
    return loadedModule.exports;
  }
${SHARED_GLUE}
${body}
})(globalThis);
`;
}

export function createIOSNativeRulesBundle() {
  return createRulesScript({
    header: `// Generated by scripts/build-ios-native-rules.mjs. Do not edit by hand.
// No entry points remain: plan 019 R1–R3 moved every rule iOS used to Swift.
// Plan 019 R4 deletes this bundle and the steps that build and ship it.`,
    moduleNames: ["./countdown"],
    body: `
  global.OWCNative = {};
`,
  });
}

export function writeIOSNativeRulesBundle(
  outputPath = resolve("src-mobile/ios/App/App/Resources/CountdownRules.js")
) {
  const bundle = createIOSNativeRulesBundle();
  mkdirSync(dirname(outputPath), { recursive: true });
  writeFileSync(outputPath, bundle, "utf8");
  return bundle;
}

if (process.argv[1] === new URL(import.meta.url).pathname) {
  writeIOSNativeRulesBundle();
}
