import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import ts from "typescript";

const moduleSources = {
  "./countdown": resolve("lib/countdown.ts"),
  "./reminders": resolve("lib/reminders.ts"),
  "./summary": resolve("lib/summary.ts"),
  "./watch-projection": resolve("lib/watch-projection.ts"),
};

function compileModule(path) {
  const source = readFileSync(path, "utf8");
  return ts.transpileModule(source, {
    compilerOptions: {
      module: ts.ModuleKind.CommonJS,
      target: ts.ScriptTarget.ES2020,
      removeComments: false,
    },
    fileName: path,
    reportDiagnostics: true,
  });
}

// Input normalisation and current-shift resolution. The bundle's remaining
// entries and the schedule-rule oracle both need it, so it exists once.
const SHARED_GLUE = `
  const countdown = require("./countdown");

  function shiftOptions(input) {
    return {
      breakStartTime: input.breakStartTime || null,
      breakDurationMinutes: input.breakDurationMinutes || 0,
      overtimeEndAtMs: input.overtimeEndAtMs || null,
    };
  }

  function inputTimeZone(input) {
    return typeof input.timeZoneIdentifier === "string" && input.timeZoneIdentifier.trim()
      ? input.timeZoneIdentifier.trim()
      : null;
  }

  function resolveCurrentShift(input) {
    const options = shiftOptions(input);
    const timeZone = inputTimeZone(input);
    const live = countdown.buildShiftTimeline(
      input.startTime,
      input.endTime,
      new Date(input.nowMs),
      options,
      timeZone
    );
    const ended = countdown.findEndedShiftOnEndCalendarDay({
      startTime: input.startTime,
      endTime: input.endTime,
      nowMs: input.nowMs,
      workdays: input.workdays,
      schedule: input.schedule || null,
      options,
      forcedWorkdayStartMs: input.forcedWorkdayStartMs || null,
      timeZone,
    });
    const liveStart = countdown.getShiftStartAtMs(live);
    const liveEnd = countdown.getShiftEndAtMs(live);
    // Settlement of last night's overnight only applies until tonight's
    // window actually starts. A rest-day 22:00–06:00 on Saturday would
    // otherwise stay pinned to Friday's 06:00 end all evening, including a
    // forced Saturday night run.
    const liveIsOpen = input.nowMs >= liveStart && input.nowMs < liveEnd;
    if (
      ended &&
      countdown.getShiftStartAtMs(ended) !== liveStart &&
      !liveIsOpen
    ) {
      return ended;
    }
    return live;
  }

  function startOfLocalDayMs(date, timeZone) {
    return countdown.startOfCivilDayMs(
      date instanceof Date ? date.getTime() : Number(date),
      timeZone || null
    );
  }

  function isScheduledShift(input, shift) {
    return countdown.isScheduledWorkday(
      new Date(countdown.getShiftStartAtMs(shift)),
      input.workdays,
      input.schedule || null,
      inputTimeZone(input)
    );
  }
`;

/**
 * A self-contained script evaluating the named `lib/` modules, the shared
 * glue, then `body`, which assigns its entry points onto `global`.
 */
export function createRulesScript({ header, moduleNames, body }) {
  const compiled = moduleNames.map((name) => {
    const path = moduleSources[name];
    const result = compileModule(path);
    const errors = (result.diagnostics ?? []).filter(
      (diagnostic) => diagnostic.category === ts.DiagnosticCategory.Error
    );
    if (errors.length > 0) {
      throw new Error(
        `Could not compile ${path}: ${errors
          .map((diagnostic) => diagnostic.messageText)
          .join(", ")}`
      );
    }
    return `${JSON.stringify(name)}: function(module, exports, require) {\n${result.outputText}\n}`;
  });

  return `${header}
(function(global) {
  "use strict";
  const factories = {${compiled.join(",\n")}};
  const cache = Object.create(null);
  function require(name) {
    if (cache[name]) return cache[name].exports;
    const factory = factories[name];
    if (!factory) throw new Error("Unknown bundled module: " + name);
    const loadedModule = { exports: {} };
    cache[name] = loadedModule;
    factory(loadedModule, loadedModule.exports, require);
    return loadedModule.exports;
  }
${SHARED_GLUE}
${body}
})(globalThis);
`;
}

export function createIOSNativeRulesBundle() {
  return createRulesScript({
    header: `// Generated by scripts/build-ios-native-rules.mjs. Do not edit by hand.
// SwiftUI calls this JavaScriptCore bundle for the rules that have not moved
// to Swift yet (plan 019 R2 and R3): reminders, summaries and income. Shift
// resolution, snapshots and expansion are Swift since R1 (ScheduleRules.swift).`,
    moduleNames: ["./countdown", "./reminders", "./summary"],
    body: `
  const reminders = require("./reminders");
  const summary = require("./summary");

  global.OWCNative = {
    summarize(inputJSON) {
      const input = JSON.parse(inputJSON);
      const asOf = new Date(input.asOfMs);
      const timeZone = typeof input.timeZoneIdentifier === "string" && input.timeZoneIdentifier.trim()
        ? input.timeZoneIdentifier.trim()
        : undefined;
      // An explicit window start wins over the period name. The Records tab
      // draws week and month grids with the locale's own first weekday, so the
      // window it summarises is not always the ISO week the period name
      // derives; it passes the boundary it already drew instead.
      // Number(null) is 0, a valid epoch, so a null must not reach it.
      const explicitStartMs = input.periodStartMs == null ? NaN : Number(input.periodStartMs);
      const periodStart = Number.isFinite(explicitStartMs)
        ? new Date(explicitStartMs)
        : timeZone
          ? new Date(
            input.period === "year"
              ? countdown.zonedYearStartMs(input.asOfMs, timeZone)
              : countdown.zonedWeekStartMs(input.asOfMs, timeZone)
          )
          : input.period === "year"
            ? summary.startOfYear(asOf)
            : summary.startOfWeek(asOf);
      return JSON.stringify(summary.summarize({
        periodStart,
        asOf,
        workdays: input.workdays,
        schedule: input.schedule || null,
        currentShiftStart: new Date(input.currentShiftStartMs),
        currentShiftEnd: new Date(input.currentShiftEndMs),
        plannedDailyHours: input.plannedDailyHours,
        todayProgress: input.todayProgress,
        dailySalary: input.dailySalary,
        todayEffectiveHours: input.todayEffectiveHours,
        todayPayRatio: input.todayPayRatio,
        timeZone,
      }));
    },

    recordsIncome(inputJSON) {
      const input = JSON.parse(inputJSON);
      const dailySalary = countdown.getDailySalary(
        String(input.salaryAmount ?? ""),
        input.salaryType,
        input.monthlyWorkingDays,
        input.annualBonusMonths || 0
      );
      return JSON.stringify({
        earnings: summary.completedWorkdayIncome(
          input.completedWorkdays,
          dailySalary
        ),
      });
    },

    salaryMonthlyEquivalent(inputJSON) {
      const input = JSON.parse(inputJSON);
      return JSON.stringify({
        amount: countdown.getMonthlySalaryEquivalent(
          String(input.salaryAmount ?? ""),
          input.salaryType,
          input.monthlyWorkingDays,
          input.annualBonusMonths || 0
        ),
      });
    },

    lifetimeIncome(inputJSON) {
      return JSON.stringify(summary.projectLifetimeGrossIncome(JSON.parse(inputJSON)));
    },

    recordsActualForecast(inputJSON) {
      return JSON.stringify(summary.summarizeRecordsActualAndForecast(JSON.parse(inputJSON)));
    },

    reminders(inputJSON) {
      const input = JSON.parse(inputJSON);
      const shift = resolveCurrentShift(input);
      const nextShift = countdown.findNextShiftTimeline({
        startTime: input.startTime,
        endTime: input.endTime,
        workdays: input.workdays,
        schedule: input.schedule || null,
        afterMs: Math.max(input.nowMs, countdown.getShiftEndAtMs(shift)),
        options: {
          breakStartTime: input.breakStartTime || null,
          breakDurationMinutes: input.breakDurationMinutes || 0,
        },
        timeZone: inputTimeZone(input),
      });
      const project = (timeline, scope) =>
        reminders
          .buildShiftReminders(timeline, input.reminderInputs)
          .map((reminder) => ({
            ...reminder,
            id: scope + ":" + countdown.getShiftEndAtMs(timeline) + ":" + reminder.id,
          }));
      return JSON.stringify(
        [
          ...project(shift, "current"),
          ...(nextShift ? project(nextShift, "next") : []),
        ].sort((left, right) => left.atMs - right.atMs)
      );
    },

    shouldPromptApplyToday(requestJSON) {
      const request = JSON.parse(requestJSON);
      const current = resolveCurrentShift(request.current);
      const candidate = resolveCurrentShift(request.candidate);
      const currentIsScheduled = isScheduledShift(request.current, current);
      const candidateIsScheduled = isScheduledShift(request.candidate, candidate);

      if (request.kind === "lunch") {
        // Even a finished lunch still changes today's Records allocation. Ask
        // instead of silently making it effective tomorrow while the rest of
        // the edited schedule appears to have reached today.
        return currentIsScheduled || candidateIsScheduled;
      }

      // A settled shift is still today's durable Records row. The user must be
      // able to decide whether a later settings edit revises that row or starts
      // with the next shift.
      return currentIsScheduled || candidateIsScheduled;
    },
  };
`,
  });
}

export function writeIOSNativeRulesBundle(
  outputPath = resolve("src-mobile/ios/App/App/Resources/CountdownRules.js")
) {
  const bundle = createIOSNativeRulesBundle();
  mkdirSync(dirname(outputPath), { recursive: true });
  writeFileSync(outputPath, bundle, "utf8");
  return bundle;
}

if (process.argv[1] === new URL(import.meta.url).pathname) {
  writeIOSNativeRulesBundle();
}
